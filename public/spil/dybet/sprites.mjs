/** Tegner en sprite til et canvas (`lavCanvas(b, h)` skal give et canvas, i browseren document.createElement). */
export function tegn(sprite, lavCanvas, skala = 1, tone = null) {
  const h = sprite.raekker.length, b = sprite.raekker[0].length;
  const c = lavCanvas(b * skala, h * skala);
  const ctx = c.getContext('2d');
  for (let y = 0; y < h; y++) for (let x = 0; x < b; x++) {
    const ch = sprite.raekker[y][x];
    if (ch === '.' || ch === undefined) continue;
    ctx.fillStyle = tone || sprite.farver[ch] || '#f0f';
    ctx.fillRect(x * skala, y * skala, skala, skala);
  }
  return c;
}

/** Tjek til testene: alle rækker lige lange, alle tegn har en farve. */
export function tjekSprites() {
  const fejl = [];
  for (const [navn, s] of Object.entries({ ...MONSTER_SPRITES, ...TING_SPRITES, ...IKONER })) {
    const b = s.raekker[0].length;
    s.raekker.forEach((r, i) => {
      if (r.length !== b) fejl.push(`${navn} række ${i} har længde ${r.length}, ikke ${b}`);
      for (const ch of r) if (ch !== '.' && !s.farver[ch]) fejl.push(`${navn} bruger ukendt tegn '${ch}'`);
    });
  }
  return fejl;
}
